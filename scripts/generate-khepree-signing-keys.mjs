/**
 * Build-time generator: embed trusted license signing PUBLIC keys in main bundle.
 *
 * Usage:
 *   node scripts/generate-khepree-signing-keys.mjs
 *   node scripts/generate-khepree-signing-keys.mjs --require-production
 *
 * CI env (one or more):
 *   KHEPREE_LICENSE_SIGNING_PUBLIC_KEY
 *   KHEPREE_LICENSE_SIGNING_PUBLIC_KEY_LEGACY  (rotation overlap)
 *   KHEPREE_TRUSTED_SIGNING_KEYS_JSON          ({ "keyId": "spkiBase64", ... })
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  collectSigningKeysFromEnv,
  formatKeyIdsForLog,
} from './khepree-signing-key-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src/main/khepree/generated');
const outFile = path.join(outDir, 'trusted-signing-keys.ts');

const requireProduction = process.argv.includes('--require-production');

let keys;
try {
  keys = collectSigningKeysFromEnv();
} catch (error) {
  console.error(`[khepree-signing] ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}

const keyIds = Object.keys(keys).sort();

if (requireProduction && keyIds.length === 0) {
  console.error(
    '[khepree-signing] Production build requires at least one trusted signing public key. ' +
      'Set KHEPREE_LICENSE_SIGNING_PUBLIC_KEY (and optional _LEGACY or KHEPREE_TRUSTED_SIGNING_KEYS_JSON).',
  );
  process.exit(1);
}

const entries = keyIds
  .map((keyId) => `  '${keyId}': '${keys[keyId]}',`)
  .join('\n');

const source = `/**
 * AUTO-GENERATED by scripts/generate-khepree-signing-keys.mjs — do not edit.
 * PUBLIC keys only. Regenerated at build time from CI environment variables.
 */
export const KHEPREE_TRUSTED_SIGNING_KEYS_GENERATED: Readonly<Record<string, string>> = {
${entries}
} as const;

/** Trusted keyIds embedded in this build (for release verification). */
export const KHEPREE_TRUSTED_SIGNING_KEY_IDS: readonly string[] = ${JSON.stringify(keyIds)} as const;
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, source, 'utf8');

console.log(
  `[khepree-signing] Wrote ${path.relative(root, outFile)} with keyIds: ${formatKeyIdsForLog(keyIds)}`,
);
